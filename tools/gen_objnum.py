"""Generate include/objnum_ru.h: number forms of the head nouns of Russian
object names (gender, genitive singular, nominative plural, genitive
plural), used by objnam.c for "3 золотых зелья".  Needs pymorphy3.
    python -X utf8 tools/gen_objnum.py"""
import re, os
import pymorphy3

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ADJ = ('ый', 'ий', 'ой', 'ая', 'яя', 'ое', 'ее', 'ые')
PREPS = {'с', 'со', 'из', 'в', 'во', 'без', 'под', 'на', 'для', 'от', 'к'}
# pymorphy has no or wrong forms: nom -> (gender, gen_sg, nom_pl, gen_pl)
MANUAL = {
    'юми': ('m', 'юми', 'юми', 'юми'),
    'цуруги': ('m', 'цуруги', 'цуруги', 'цуруги'),
    'крис-нож': ('m', 'крис-ножа', 'крис-ножи', 'крис-ножей'),
    'шапочка-череп': ('f', 'шапочки-черепа', 'шапочки-черепа', 'шапочек-черепов'),
    'сабля': ('f', 'сабли', 'сабли', 'сабель'),
    'яйцо': ('n', 'яйца', 'яйца', 'яиц'),
    'лембас': ('m', 'лембаса', 'лембасы', 'лембасов'),
    'сюрикен': ('m', 'сюрикена', 'сюрикены', 'сюрикенов'),
    'криснож': ('m', 'крисножа', 'крисножи', 'крисножей'),
    'кержамес': ('m', 'кержамеса', 'кержамесы', 'кержамесов'),
    'вуж': ('m', 'вужа', 'вужи', 'вужей'),
    'фошар': ('m', 'фошара', 'фошары', 'фошаров'),
    'спетум': ('m', 'спетума', 'спетумы', 'спетумов'),
    'ронсар': ('m', 'ронсара', 'ронсары', 'ронсаров'),
    'корнуфаум': ('m', 'корнуфаума', 'корнуфаумы', 'корнуфаумов'),
    'бардиш': ('m', 'бардиша', 'бардиши', 'бардишей'),
    'аклис': ('m', 'аклиса', 'аклисы', 'аклисов'),
    'протазан': ('m', 'протазана', 'протазаны', 'протазанов'),
    'биль-гизарма': ('f', 'биль-гизармы', 'биль-гизармы', 'биль-гизарм'),
    'бирюза': ('f', 'бирюзы', 'бирюзы', 'бирюз'),
    'золото': ('n', 'золота', 'золота', 'золот'),
    'фрикаделька': ('f', 'фрикадельки', 'фрикадельки', 'фрикаделек'),
}


def head(s):
    ws = s.split()
    for i, w in enumerate(ws):
        w = w.strip(',.;:()')
        if not w or w[0].isdigit() or w[0] in '+-':
            continue
        if w.lower() in PREPS:
            return None
        b = w[:-2] if len(w) >= 6 and w.endswith('ся') else w
        adj = len(b) >= 4 and b.endswith(ADJ)
        if len(b) >= 4 and b.endswith('ие'):
            adj = i + 1 < len(ws) and ws[i + 1][-1:] in ('ы', 'и')
        if not adj:
            return w
    return None


def lits(path):
    t = open(os.path.join(ROOT, path), 'rb').read().decode('cp1251')
    return re.findall(r'"([^"]*)"', t)


def main():
    m = pymorphy3.MorphAnalyzer()
    names = set()
    for f in ('include/objects.h', 'src/objnam.c'):
        for s in lits(f):
            if re.search('[а-яё]', s) and '%' not in s and chr(92) not in s:
                names.add(s.strip())
    heads, bad = {}, []
    G = {'masc': 'm', 'femn': 'f', 'neut': 'n'}
    for n in sorted(names):
        h = head(n)
        if not h or len(h) < 3 or not re.fullmatch('[а-яё-]+', h) or h in heads:
            continue
        if h in MANUAL:
            heads[h] = MANUAL[h]
            continue
        cand = [p for p in m.parse(h) if 'NOUN' in p.tag and 'nomn' in p.tag
                and 'sing' in p.tag and p.word == h]
        if not cand:
            continue  # not a singular noun (verbs, genitive tails, plurals)
        p = cand[0]
        gs, np_, gp = (p.inflect({'gent', 'sing'}), p.inflect({'nomn', 'plur'}),
                       p.inflect({'gent', 'plur'}))
        if not (gs and np_ and gp) or p.tag.gender not in G:
            bad.append(h)
            continue
        heads[h] = (G[p.tag.gender], gs.word, np_.word, gp.word)
    out = ['/* objnum_ru.h: number forms of head nouns of object names:',
           ' * nominative, gender, genitive sg, nominative pl, genitive pl.',
           ' * Generated by tools/gen_objnum.py (pymorphy3); do not edit.  CP1251. */',
           '', 'static const struct ru_num_name {',
           '    const char *nom;', '    char gend;',
           '    const char *gen_sg, *nom_pl, *gen_pl;',
           '} ru_num_names[] = {']
    for h in sorted(heads):
        g, a, b, c = heads[h]
        out.append('    { "%s", \'%s\', "%s", "%s", "%s" },' % (h, g, a, b, c))
    out.append('};')
    open(os.path.join(ROOT, 'include/objnum_ru.h'), 'wb').write(
        ('\r\n'.join(out) + '\r\n').encode('cp1251'))
    print(len(heads), 'nouns; unresolved:', ' '.join(bad))


main()
